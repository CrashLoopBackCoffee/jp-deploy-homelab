import dataclasses

import pulumi as p
import pulumi_kubernetes as k8s

BARMAN_PLUGIN = 'barman-cloud.cloudnative-pg.io'


@dataclasses.dataclass(frozen=True)
class BackupTarget:
    """S3-compatible bucket receiving base backups and WAL; each database gets its own prefix."""

    endpoint: str
    bucket: str
    access_key_id: p.Input[str]
    secret_access_key: p.Input[str]
    retention_policy: str = '14d'
    # Six-field CloudNativePG cron expression (seconds first).
    schedule: str = '0 0 3 * * *'


@dataclasses.dataclass(frozen=True)
class CnpgDatabase:
    cluster: k8s.apiextensions.CustomResource
    # Read-write Service and the Secret CloudNativePG generates for the application owner
    # (keys `username`, `password`, `dbname`, `host`, `port`, `uri`).
    host: str
    app_secret_name: str
    port: int = 5432


def create_cnpg_database(
    name: str,
    *,
    database: str,
    owner: str,
    image_version: str,
    storage_size: str,
    storage_class: p.Input[str],
    backup: BackupTarget,
    k8s_opts: p.ResourceOptions,
) -> CnpgDatabase:
    """Create a single-instance CloudNativePG cluster with Barman plugin backups.

    Requires the CloudNativePG operator and the Barman Cloud plugin from the kubernetes stack, and
    `k8s_opts` must carry a provider scoped to the target namespace. The owner's password is
    generated by CloudNativePG, so callers read it from the `<name>-app` Secret.
    """
    store_name = f'{name}-store'
    credentials = k8s.core.v1.Secret(
        f'{name}-backup-credentials',
        metadata={'name': f'{name}-backup-credentials'},
        string_data={
            'ACCESS_KEY_ID': backup.access_key_id,
            'ACCESS_SECRET_KEY': backup.secret_access_key,
        },
        opts=k8s_opts,
    )
    store = k8s.apiextensions.CustomResource(
        store_name,
        api_version='barmancloud.cnpg.io/v1',
        kind='ObjectStore',
        metadata={'name': store_name},
        spec={
            'configuration': {
                'destinationPath': f's3://{backup.bucket}/{name}/',
                'endpointURL': backup.endpoint,
                's3Credentials': {
                    'accessKeyId': {'name': credentials.metadata.name, 'key': 'ACCESS_KEY_ID'},
                    'secretAccessKey': {
                        'name': credentials.metadata.name,
                        'key': 'ACCESS_SECRET_KEY',
                    },
                },
                'wal': {'compression': 'gzip'},
            },
            # QuObjects rejects boto3's optional checksum headers with InvalidDigest.
            'instanceSidecarConfiguration': {
                'env': [
                    {'name': 'AWS_REQUEST_CHECKSUM_CALCULATION', 'value': 'when_required'},
                    {'name': 'AWS_RESPONSE_CHECKSUM_VALIDATION', 'value': 'when_required'},
                ],
            },
            'retentionPolicy': backup.retention_policy,
        },
        opts=p.ResourceOptions.merge(k8s_opts, p.ResourceOptions(depends_on=[credentials])),
    )
    cluster = k8s.apiextensions.CustomResource(
        name,
        api_version='postgresql.cnpg.io/v1',
        kind='Cluster',
        # Applications depending on the database should not start before it is serving.
        metadata={'name': name, 'annotations': {'pulumi.com/waitFor': 'condition=Ready'}},
        spec={
            'instances': 1,
            'imageName': f'ghcr.io/cloudnative-pg/postgresql:{image_version}',
            'storage': {'size': storage_size, 'storageClass': storage_class},
            'bootstrap': {'initdb': {'database': database, 'owner': owner}},
            'plugins': [
                {
                    'name': BARMAN_PLUGIN,
                    'isWALArchiver': True,
                    'parameters': {'barmanObjectName': store_name},
                }
            ],
        },
        opts=p.ResourceOptions.merge(k8s_opts, p.ResourceOptions(depends_on=[store])),
    )
    k8s.apiextensions.CustomResource(
        f'{name}-backup',
        api_version='postgresql.cnpg.io/v1',
        kind='ScheduledBackup',
        metadata={'name': f'{name}-backup'},
        spec={
            'schedule': backup.schedule,
            'immediate': True,
            'backupOwnerReference': 'self',
            'cluster': {'name': name},
            'method': 'plugin',
            'pluginConfiguration': {'name': BARMAN_PLUGIN},
        },
        opts=p.ResourceOptions.merge(k8s_opts, p.ResourceOptions(depends_on=[cluster])),
    )
    return CnpgDatabase(cluster=cluster, host=f'{name}-rw', app_secret_name=f'{name}-app')
